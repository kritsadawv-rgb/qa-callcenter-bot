# ตั้งค่าโมเดลให้เป็นโหมดไม้บรรทัด (เป๊ะๆ ไม่มีความคิดสร้างสรรค์)
generation_config = {"temperature": 0.0, "top_p": 1, "top_k": 1}
model = genai.GenerativeModel(
    model_name="gemini-1.5-flash-latest",
    generation_config=generation_config,
    system_instruction=SYSTEM_PROMPT
)

st.title("🛠️ ระบบ AI ตรวจรายงาน Call Center")

mode = st.radio("โหมดการทำงาน:", ["ตรวจงานทั่วไป", "ตรวจคำผิด", "เรียบเรียงคำพูด"])

report_text = st.text_area("วางข้อความรายงานที่นี่:", height=200)

if st.button("ตรวจสอบรายงาน"):
    if report_text:
        with st.spinner('กำลังตรวจสอบอย่างละเอียด...'):
            try:
                # ปรับคำสั่งตามโหมดที่เลือก
                if mode == "ตรวจคำผิด":
                    user_prompt = f"คำสั่ง: ตรวจคำผิด\nข้อความ:\n{report_text}"
                elif mode == "เรียบเรียงคำพูด":
                    user_prompt = f"คำสั่ง: เรียบเรียงคำพูด\nข้อความ:\n{report_text}"
                else:
                    user_prompt = f"ข้อความ:\n{report_text}"
                
                response = model.generate_content(user_prompt)
                st.success("✅ ตรวจสอบเสร็จสิ้น")
                st.write(response.text)
            except Exception as e:
                st.error(f"เกิดข้อผิดพลาด: {e}")
    else:
        st.warning("กรุณาวางข้อความรายงานก่อนกดตรวจสอบ")
